/**
 * Phase 4 prompts — three persona system prompts, one consolidator system
 * prompt, plus a short round-robin instruction snippet.
 *
 * Body section names mirror the Claude Design handoff (2026-05-06): each
 * persona has a fixed three-section body so the renderer can dispatch on
 * structure rather than free-form headings.
 *
 * The neutral prompt is load-bearing per the issue Notes — a weak neutral
 * collapses the phase into "three LLMs each list risks." The explicit
 * filtering framing + dismissedRisks usage examples are the lever.
 */

const SHARED_OUTPUT_PREAMBLE = [
  "Your output schema is enforced by the framework. Return a single JSON",
  "object matching the schema. Do not include any other text.",
].join("\n");

const SHARED_METRICS_NOTE = [
  "The `metrics` object is uniform across all three risk personas with six",
  "required keys: `stance`, `structuralChange`, `scopeChange`,",
  "`exitDiscipline`, `stopMechanics`, `followOn`. Fill the keys your",
  'posture uses with meaningful short strings; fill the rest with "—"',
  "(em-dash). Do not omit any key.",
].join("\n");

