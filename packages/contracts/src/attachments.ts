/**
 * Attachments: the one limits set the composer and the server both read, and
 * the one helper that builds and parses a stored file's reference.
 *
 * A file a person attaches is uploaded once and kept in the server's blob
 * store. Everything after the upload carries a reference to it in
 * `FileContent.data`, in the form `fsd-blob:<id>`. This module is the only
 * place that knows that form: nothing else builds it, string-matches it, or
 * reads `data` as bytes (the engine's resolver turns a reference into bytes).
 */

/** The scheme a stored file's reference starts with. Module-private: use the helpers. */
const BLOB_REF_SCHEME = "fsd-blob:";

/** What a blob id may contain. Ids are generated by the server; this also keeps one out of a path. */
const BLOB_ID_PATTERN = /^b_[A-Za-z0-9]{8,64}$/;

/** True when `id` has the shape the server gives a blob. */
export function isBlobId(id: string): boolean {
  return BLOB_ID_PATTERN.test(id);
}

/** The reference a stored file's `FileContent.data` carries: `fsd-blob:<id>`. */
export function toBlobRef(id: string): string {
  if (!isBlobId(id)) throw new TypeError(`"${id}" is not a blob id`);
  return `${BLOB_REF_SCHEME}${id}`;
}

/** The blob id inside a reference, or `undefined` when `data` is not one. */
export function parseBlobRef(data: string): string | undefined {
  if (!data.startsWith(BLOB_REF_SCHEME)) return undefined;
  const id = data.slice(BLOB_REF_SCHEME.length);
  return isBlobId(id) ? id : undefined;
}

/** Image types an attachment may have in v1. */
export const ATTACHMENT_IMAGE_TYPES = ["image/png", "image/jpeg", "image/webp", "image/gif"] as const;

/** Document types an attachment may have in v1. */
export const ATTACHMENT_DOCUMENT_TYPES = ["application/pdf"] as const;

/** A media type an attachment may have. */
export type AttachmentMediaType =
  | (typeof ATTACHMENT_IMAGE_TYPES)[number]
  | (typeof ATTACHMENT_DOCUMENT_TYPES)[number];

/**
 * The media types one target (a model provider, a coding harness) can take as
 * a file. Each target fills its own; the engine refuses a type it lacks, in
 * the conversation, rather than sending text in its place.
 */
export type AttachmentAccepts = ReadonlyArray<AttachmentMediaType>;

/** The limits on what one message may carry. The composer refuses over them before send; the server refuses by name. */
export const ATTACHMENT_LIMITS = {
  /** Images in one message. */
  imagesPerMessage: 10,
  /** Documents in one message. */
  documentsPerMessage: 5,
  /** Bytes in one file, as picked. */
  maxFileBytes: 20 * 1024 * 1024,
  /** Pages in one PDF, counted on the server before any model call. */
  maxPdfPages: 100,
  /** Bytes of text from one text-like file, or from a PDF's text sent to a target that can't read PDFs. */
  maxTextBytes: 200 * 1024,
  /** How long an upload no message has claimed is kept, at least. */
  unclaimedTtlMs: 24 * 60 * 60 * 1000
} as const;

/** Whether an attachment of `mediaType` counts against the image or the document limit, or is refused. */
export function attachmentKind(mediaType: string): "image" | "document" | undefined {
  const type = normalizeMediaType(mediaType);
  if ((ATTACHMENT_IMAGE_TYPES as readonly string[]).includes(type)) return "image";
  if ((ATTACHMENT_DOCUMENT_TYPES as readonly string[]).includes(type)) return "document";
  return undefined;
}

/** True when an attachment may have `mediaType`. HEIC, and anything not listed, is refused. */
export function isAttachmentMediaType(mediaType: string): mediaType is AttachmentMediaType {
  return attachmentKind(mediaType) !== undefined;
}

/** `image/PNG; charset=…` → `image/png`. */
export function normalizeMediaType(mediaType: string): string {
  return (mediaType.split(";")[0] ?? "").trim().toLowerCase();
}
